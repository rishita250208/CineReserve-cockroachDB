
-- CineReserve Database Schema
-- CockroachDB-compatible schema
-- Safe to rerun: creates missing objects and preserves all existing rows.

CREATE TABLE IF NOT EXISTS Users (
    user_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    phone VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);


CREATE TABLE IF NOT EXISTS Movies (
    movie_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    genre VARCHAR(60),
    language VARCHAR(40),
    duration_minutes INT8 NOT NULL,
    certificate VARCHAR(10),
    release_date DATE,
    description VARCHAR(1000),
    CONSTRAINT chk_movie_duration CHECK (duration_minutes > 0)
);


CREATE TABLE IF NOT EXISTS Theatres (
    theatre_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    theatre_name VARCHAR(150) NOT NULL,
    city VARCHAR(80) NOT NULL,
    address VARCHAR(250)
);


CREATE TABLE IF NOT EXISTS Screens (
    screen_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    theatre_id INT8 NOT NULL,
    screen_name VARCHAR(50) NOT NULL,
    screen_type VARCHAR(30),
    CONSTRAINT fk_screen_theatre
        FOREIGN KEY (theatre_id) REFERENCES Theatres(theatre_id),
    CONSTRAINT uq_screen_name UNIQUE (theatre_id, screen_name)
);


CREATE TABLE IF NOT EXISTS Seats (
    seat_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_id INT8 NOT NULL,
    seat_row VARCHAR(5) NOT NULL,
    seat_number INT8 NOT NULL,
    seat_type VARCHAR(30),
    seat_price DECIMAL(10,2) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_seat_screen
        FOREIGN KEY (screen_id) REFERENCES Screens(screen_id),
    CONSTRAINT uq_screen_seat
        UNIQUE (screen_id, seat_row, seat_number),
    CONSTRAINT chk_seat_price CHECK (seat_price >= 0),
    CONSTRAINT chk_seat_number CHECK (seat_number > 0)
);


CREATE TABLE IF NOT EXISTS Movie_Shows (
    show_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id INT8 NOT NULL,
    screen_id INT8 NOT NULL,
    show_time TIMESTAMP NOT NULL,
    base_price DECIMAL(10,2) NOT NULL,
    CONSTRAINT fk_show_movie
        FOREIGN KEY (movie_id) REFERENCES Movies(movie_id),
    CONSTRAINT fk_show_screen
        FOREIGN KEY (screen_id) REFERENCES Screens(screen_id),
    CONSTRAINT chk_show_price CHECK (base_price >= 0)
);


CREATE TABLE IF NOT EXISTS Bookings (
    booking_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT8 NOT NULL,
    show_id INT8 NOT NULL,
    booking_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    booking_status VARCHAR(20) DEFAULT 'PENDING' NOT NULL,
    total_amount DECIMAL(10,2) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_booking_user
        FOREIGN KEY (user_id) REFERENCES Users(user_id),
    CONSTRAINT fk_booking_show
        FOREIGN KEY (show_id) REFERENCES Movie_Shows(show_id),
    CONSTRAINT chk_booking_status
        CHECK (booking_status IN ('PENDING','CONFIRMED','CANCELLED')),
    CONSTRAINT chk_booking_amount CHECK (total_amount >= 0)
);


CREATE TABLE IF NOT EXISTS Show_Seats (
    show_seat_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id INT8 NOT NULL,
    seat_id INT8 NOT NULL,
    seat_status VARCHAR(20) DEFAULT 'AVAILABLE' NOT NULL,
    CONSTRAINT fk_showseat_show
        FOREIGN KEY (show_id) REFERENCES Movie_Shows(show_id),
    CONSTRAINT fk_showseat_seat
        FOREIGN KEY (seat_id) REFERENCES Seats(seat_id),
    CONSTRAINT uq_show_seat UNIQUE (show_id, seat_id),
    CONSTRAINT chk_showseat_status
        CHECK (seat_status IN ('AVAILABLE','BOOKED','BLOCKED'))
);


CREATE TABLE IF NOT EXISTS Tickets (
    ticket_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INT8 NOT NULL,
    show_seat_id INT8 NOT NULL,
    ticket_price DECIMAL(10,2) NOT NULL,
    ticket_status VARCHAR(20) DEFAULT 'VALID' NOT NULL,
    CONSTRAINT fk_ticket_booking
        FOREIGN KEY (booking_id) REFERENCES Bookings(booking_id),
    CONSTRAINT fk_ticket_showseat
        FOREIGN KEY (show_seat_id) REFERENCES Show_Seats(show_seat_id),
    CONSTRAINT uq_ticket_showseat UNIQUE (show_seat_id),
    CONSTRAINT chk_ticket_price CHECK (ticket_price >= 0),
    CONSTRAINT chk_ticket_status CHECK (ticket_status IN ('VALID','CANCELLED'))
);


CREATE TABLE IF NOT EXISTS Payments (
    payment_id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INT8 NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    payment_status VARCHAR(20) DEFAULT 'PENDING' NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    transaction_ref VARCHAR(100) UNIQUE,
    payment_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payment_booking
        FOREIGN KEY (booking_id) REFERENCES Bookings(booking_id),
    CONSTRAINT chk_payment_status
        CHECK (payment_status IN ('PENDING','SUCCESS','FAILED','REFUNDED')),
    CONSTRAINT chk_payment_amount CHECK (amount >= 0)
);


CREATE TABLE IF NOT EXISTS User_Sessions (
    session_token VARCHAR(128) PRIMARY KEY,
    user_id INT8 NOT NULL REFERENCES Users(user_id) ON DELETE CASCADE,
    expires_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_user_sessions_expiry ON User_Sessions(expires_at);


-- Indexes for common joins and searches
CREATE INDEX IF NOT EXISTS idx_screens_theatre ON Screens(theatre_id);
CREATE INDEX IF NOT EXISTS idx_seats_screen ON Seats(screen_id);
CREATE INDEX IF NOT EXISTS idx_shows_movie ON Movie_Shows(movie_id);
CREATE INDEX IF NOT EXISTS idx_shows_screen_time ON Movie_Shows(screen_id, show_time);
CREATE INDEX IF NOT EXISTS idx_bookings_user ON Bookings(user_id);
CREATE INDEX IF NOT EXISTS idx_bookings_show ON Bookings(show_id);
CREATE INDEX IF NOT EXISTS idx_show_seats_status ON Show_Seats(show_id, seat_status);
CREATE INDEX IF NOT EXISTS idx_tickets_booking ON Tickets(booking_id);
CREATE INDEX IF NOT EXISTS idx_payments_booking ON Payments(booking_id);

-- Show availability view
CREATE OR REPLACE VIEW vw_show_availability AS
SELECT
    ms.show_id,
    m.title AS movie_title,
    th.theatre_name,
    th.city,
    sc.screen_name,
    ms.show_time,
    COUNT(ss.show_seat_id) AS total_seats,
    SUM(
        CASE
            WHEN ss.seat_status = 'AVAILABLE' THEN 1
            ELSE 0
        END
    ) AS available_seats,
    ms.base_price
FROM Movie_Shows ms
JOIN Movies m ON m.movie_id = ms.movie_id
JOIN Screens sc ON sc.screen_id = ms.screen_id
JOIN Theatres th ON th.theatre_id = sc.theatre_id
LEFT JOIN Show_Seats ss ON ss.show_id = ms.show_id
GROUP BY
    ms.show_id,
    m.title,
    th.theatre_name,
    th.city,
    sc.screen_name,
    ms.show_time,
    ms.base_price;
